/*------------------------------------------------------
COMANDO UPDATE - U
--------------------------------------------------------*/
-- NUNCA utilizar sem a cláusula WHERE.
-- O comando UPDATE é utilizado para atualizar as informações do registro de uma tabela.

-- OBS) o MySQL vinha bloqueado por padrão para UPDATE sem WHERE (safe update mode).
-- O PostgreSQL NÃO TEM essa trava. Se você esquecer o WHERE, ele atualiza a tabela inteira e pronto.
-- A proteção aqui é OUTRA, e é melhor: abra uma transação antes, confira o resultado, e só então confirme.
-- BEGIN     --> abre a transação
-- ROLLBACK  --> desfaz tudo
-- COMMIT    --> confirma tudo
-- vamos usar isso logo abaixo.

SELECT * FROM tb_funcionarios;

-- DICA DE OURO PARA NÃO ERRAR UPDATE: escreva primeiro um SELECT com o MESMO WHERE.
-- Se o SELECT trouxer só a linha que você quer mudar, aí sim troque o SELECT pelo UPDATE.
SELECT * FROM tb_funcionarios WHERE id_funcionario = 10;   -- 1 linha só: o Will Smith. Pode seguir.

-- exemplo: dar um aumento de 40 % para o funcionário id 10 Will Smith
-- atualize o salario_funcionario = converta a conta: salario_funcionario vezes 1.4 (40%) para numeric com
-- 10 números no total e duas casas decimais.
UPDATE tb_funcionarios
  SET salario_funcionario = CAST(salario_funcionario * 1.4 AS NUMERIC(10,2))
  WHERE id_funcionario = 10;
-- o banco responde: UPDATE 1  --> o número é a quantidade de linhas alteradas. Confira sempre esse número.
-- o salário do Will Smith passou de 230 para 322.


 -- Agora utilizamos a cláusula UPDATE em conjunto com SET e WHERE
 -- 9821.85
 UPDATE tb_funcionarios
    SET salario_funcionario = salario_funcionario + 1000
  WHERE id_funcionario = 1;

  -- dando aumento de 100 reais para os funcionários 4,5,8
  UPDATE tb_funcionarios
    SET salario_funcionario = salario_funcionario + 100
  WHERE id_funcionario IN (4,5,8);

  -- Verificar o aumento do salário para o funcionário 4,5,8
   SELECT * FROM tb_funcionarios
    WHERE id_funcionario IN (4,5,8);


-- AGORA O ERRO QUE TODO MUNDO COMETE UMA VEZ NA VIDA: UPDATE sem WHERE.
-- repare que NÃO vem aviso nenhum. Por isso abrimos a transação antes.
BEGIN;

    UPDATE tb_funcionarios
       SET salario_funcionario = 1;   -- esqueci o WHERE!

    -- olhe o estrago ANTES de confirmar
    SELECT id_funcionario, nome_funcionario, salario_funcionario FROM tb_funcionarios;

ROLLBACK;  -- desfaz tudo. Se tivéssemos dado COMMIT, não haveria volta.

-- conferindo que os salários voltaram ao que eram
SELECT id_funcionario, nome_funcionario, salario_funcionario FROM tb_funcionarios;

-- OBS) repare que as linhas saíram FORA DE ORDEM de id.
-- Isso não é defeito. Toda vez que o banco atualiza uma linha, ele grava uma versão nova
-- em outro lugar do arquivo, e o SELECT sem ORDER BY devolve na ordem em que encontrar.
-- REGRA: se a ordem importa para você, escreva ORDER BY. Nunca confie na ordem "natural".
SELECT id_funcionario, nome_funcionario, salario_funcionario
  FROM tb_funcionarios
 ORDER BY id_funcionario;


