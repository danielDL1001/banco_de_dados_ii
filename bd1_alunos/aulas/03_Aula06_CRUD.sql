-- OBS) no MySQL escrevíamos CREATE DATABASE IF NOT EXISTS db_universidade;
-- No PostgreSQL o CREATE DATABASE não aceita IF NOT EXISTS e não pode rodar dentro de uma transação,
-- que é justamente o que o pgAdmin faz por baixo dos panos. Por isso criamos o banco fora do script.

-- limpando a bagunça de execuções anteriores, para o script poder ser rodado de novo sem erro.
-- na primeira vez aparecem avisos (NOTICE) dizendo que as tabelas não existem. NÃO é erro, pode ignorar.
DROP TABLE IF EXISTS tb_matriculas, tb_enderecos, tb_cursos, tb_funcionarios, tb_alunos CASCADE;
DROP TYPE  IF EXISTS tp_sexo;

-- o ENUM do MySQL, no PostgreSQL, é um TIPO DE DADO que criamos antes de usar.
-- no MySQL:      sexo_funcionario ENUM('F','M')
-- no PostgreSQL: criamos o tipo e depois usamos o tipo na coluna.
CREATE TYPE tp_sexo AS ENUM ('F', 'M');

-- Utiliza-se o comando CREATE para criar tabelas no banco de dados
CREATE TABLE IF NOT EXISTS tb_alunos(
    id_aluno        INT GENERATED BY DEFAULT AS IDENTITY,
    nome_aluno      VARCHAR(250),
    email_aluno     VARCHAR(250),
    data_cadastro   TIMESTAMP,   -- no MySQL era DATETIME

    PRIMARY KEY (id_aluno)
);

-- vamos criar uma tabela de funcionários utilizando chave primária
CREATE TABLE IF NOT EXISTS tb_funcionarios(
    id_funcionario           INT GENERATED BY DEFAULT AS IDENTITY,
    nome_funcionario         VARCHAR(200),
    salario_funcionario      NUMERIC(10,2), -- total de números = 10 com duas casas decimais. No MySQL era DECIMAL(10,2)
    dta_admissao_funcionario DATE,          -- observe que utilizamos aqui o tipo _date ao invés de _timestamp
    sexo_funcionario         tp_sexo,       -- o tipo ENUM que criamos acima, próprio para valores prefixados
    dta_cadastro_funcionario TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id_funcionario)
);

-- vamos criar uma tabela de endereços com a criação de uma chave primária e uma chave estrangeira.
CREATE TABLE IF NOT EXISTS tb_enderecos (
    id_endereco    INT GENERATED BY DEFAULT AS IDENTITY,
    id_funcionario INT,
    endereco       VARCHAR(255),
    cidade         VARCHAR(100),
    estado         VARCHAR(100),

    PRIMARY KEY (id_endereco),
    FOREIGN KEY (id_funcionario) REFERENCES tb_funcionarios (id_funcionario)
);

CREATE TABLE tb_cursos(
    id_curso   INT GENERATED BY DEFAULT AS IDENTITY,
    nome_curso VARCHAR(200),
    sigla_curso CHAR(3),

    PRIMARY KEY (id_curso)
);

CREATE TABLE IF NOT EXISTS tb_matriculas (
    id_matricula   INT GENERATED BY DEFAULT AS IDENTITY,
    id_aluno       INT NOT NULL,
    id_curso       INT NOT NULL,
    data_matricula TIMESTAMP,

    PRIMARY KEY (id_matricula),
    FOREIGN KEY (id_aluno) REFERENCES tb_alunos (id_aluno),
    FOREIGN KEY (id_curso) REFERENCES tb_cursos (id_curso)
);


