-- POR QUE DEU ERRO? Aqui está a maior diferença entre MySQL e PostgreSQL no autoincremento.
-- No MySQL, quando você informa o id na mão, o AUTO_INCREMENT "olha" para o maior valor da tabela
-- e continua a partir dali.
-- No PostgreSQL, o gerador de números é um objeto SEPARADO da tabela, chamado SEQUENCE.
-- Ele NÃO fica olhando o conteúdo da tabela. Ele estava no 1, tentou gravar 1, e bateu na chave primária.

-- vendo o estado da sequence: qual foi o último número que ela entregou.
