 -- A cláusula DELETE é utilizada para excluir um registro
 -- sempre utilizar com a instrução WHERE.
 -- a mesma dica do UPDATE vale aqui: primeiro o SELECT com o WHERE, depois o DELETE.
 -- E aqui vale em dobro: DELETE sem WHERE apaga a tabela INTEIRA, e não tem desfazer (a não ser com BEGIN/ROLLBACK).

 DELETE FROM tb_funcionarios
 WHERE id_funcionario = 1;

 -- Verificar a exclusão com o comando select
 SELECT * FROM tb_funcionarios;


-- EXCLUIR 5 REGISTROS DE UMA TABELA.
-- no MySQL escrevíamos:  DELETE FROM tb_funcionarios LIMIT 5;
-- o PostgreSQL NÃO aceita LIMIT no DELETE. E com razão: "apague 5 quaisquer" não é uma regra,
-- é um sorteio. O banco exige que você diga QUAIS 5.
-- a forma correta é escolher os 5 primeiro, com critério e ordem, e apagar exatamente esses.
DELETE FROM tb_funcionarios
 WHERE id_funcionario IN (
        SELECT id_funcionario
          FROM tb_funcionarios
         ORDER BY id_funcionario
         LIMIT 5
 );

-- conferindo quem sobrou
SELECT * FROM tb_funcionarios;
-- resultado esperado: 4 funcionários (ids 7, 8, 9 e 10).
-- tínhamos 10, apagamos o id 1 e depois os 5 menores ids que sobraram (2, 3, 4, 5 e 6).

-- COMO LER O DELETE ACIMA, de dentro para fora:
--   1) o SELECT entre parênteses roda primeiro e devolve uma lista: 2, 3, 4, 5, 6
--   2) o DELETE apaga quem estiver nessa lista:  WHERE id_funcionario IN (2, 3, 4, 5, 6)
-- Um SELECT dentro de outro comando chama-se SUBCONSULTA (ou subquery).


