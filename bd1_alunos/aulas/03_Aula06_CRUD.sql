-- OBS) ESTA LINHA VAI DAR ERRO DE PROPÓSITO. Execute e leia a mensagem:
--      ERROR:  duplicate key value violates unique constraint "tb_alunos_pkey"
--      DETAIL:  Key (id_aluno)=(1) already exists.
