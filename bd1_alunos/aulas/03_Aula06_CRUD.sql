/*-----------------------------------------------------------------------------------
Siglas da modelagem, e como elas ficam no PostgreSQL.
------------------------------------------------------------------------------------*/

-- PK: Primary Key (Chave Primária) - Indica que a coluna é a chave primária da tabela, usada para identificar exclusivamente cada registro. Ela deve conter valores únicos e não pode ser nula.

-- NN: Not Null (Não Nulo) - Indica que a coluna não pode ter valores nulos, ou seja, deve ser preenchida com algum valor em cada registro.

-- UQ: Unique (Único) - Indica que os valores na coluna devem ser únicos, ou seja, não podem ser duplicados em diferentes registros.

-- B: BLOB (Binary Large Object) - no PostgreSQL o tipo equivalente chama-se BYTEA. Armazena dados binários de tamanho variável.

-- UN: Unsigned (Não Sinalizado) - NÃO EXISTE no PostgreSQL. Para impedir números negativos usamos uma restrição CHECK (coluna >= 0).

-- ZF: Zero Fill (Preenchimento com Zeros) - NÃO EXISTE no PostgreSQL. Isso é formatação de saída, e se resolve na consulta com a função LPAD.

-- AI: Auto Increment (Incremento Automático) - no PostgreSQL chama-se GENERATED AS IDENTITY. Indica que a coluna é
--     incrementada automaticamente a cada novo registro inserido na tabela.
--     GENERATED ALWAYS AS IDENTITY     = o banco manda, você NÃO pode informar o valor.
--     GENERATED BY DEFAULT AS IDENTITY = o banco gera, mas você PODE informar o valor. É o mais parecido com o MySQL.

-- G: Generated (Gerado) - existe no PostgreSQL como GENERATED ALWAYS AS (expressão) STORED. O valor da coluna é
--    calculado a partir de outras colunas, em vez de ser fornecido explicitamente.

