/* =============================================================================
   4. CRIAÇÃO DAS TABELAS (colunas e obrigatoriedade; PK/FK/UNIQUE em 5-7)
   Ordem alfabética: dependências são resolvidas porque as FKs só são criadas
   na seção 6.
