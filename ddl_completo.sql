-- 9.1 Contagens esperadas: 21 tabelas, 21 PKs, 22 FKs, 4 UNIQUE
SELECT
  (SELECT count(*) FROM information_schema.tables
    WHERE table_schema='public' AND table_type='BASE TABLE')          AS tabelas,   -- esperado 21
  (SELECT count(*) FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace
    WHERE n.nspname='public' AND c.contype='p')                       AS pks,       -- esperado 21
  (SELECT count(*) FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace
    WHERE n.nspname='public' AND c.contype='f')                       AS fks,       -- esperado 22
  (SELECT count(*) FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace
    WHERE n.nspname='public' AND c.contype='u')                       AS uniques;   -- esperado 4

-- 9.2 Tabelas sem chave primária (esperado: nenhuma linha)
SELECT c.relname
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname='public' AND c.relkind='r'
  AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conrelid=c.oid AND k.contype='p');

-- 9.3 Relação das FKs (tabela.coluna -> referenciada)
SELECT conrelid::regclass AS tabela, conname,
       pg_get_constraintdef(oid) AS definicao
FROM pg_constraint
WHERE contype='f' AND connamespace='public'::regnamespace
ORDER BY 1, 2;

-- 9.4 Colunas por tabela (conferir com o modelo)
SELECT table_name, count(*) AS colunas
FROM information_schema.columns WHERE table_schema='public'
GROUP BY table_name ORDER BY table_name;

-- 9.5 Índices existentes
SELECT tablename, indexname, indexdef
FROM pg_indexes WHERE schemaname='public' ORDER BY tablename, indexname;

-- 9.6 Domínio criado
SELECT typname, typtype, format_type(typbasetype, NULL) AS base
FROM pg_type WHERE typname='vinculo_t';


