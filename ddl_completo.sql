/* =============================================================================
   8. CRIAÇÃO DOS ÍNDICES (justificativas e evidências nas seções 10-11)
   =============================================================================
   Índices JÁ existentes por constraint (não duplicar): todas as PKs, e
   uq_aluno_email, uq_professor_matricula, uq_matricula_aluno_turma,
   uq_historico_matricula.

   NÃO indexados de propósito (tabelas pequenas, seq scan é mais barato e cada
   índice custaria em INSERT/UPDATE/DELETE): estado.id_pais, cidade.id_estado,
   predio.id_cidade/id_campus, bloco.id_predio, sala.id_bloco, curso.id_campus,
   curriculo.id_curso, pais_feriado.fk_id_feriado; também
   curriculo_disciplina/pre_requisito/pais_feriado pela 1ª coluna (cobertas pela
   PK composta) e matricula.id_aluno / historico.id_matricula (cobertos pelos
   UNIQUE). */

-- I1: lista de alunos de uma turma (diário de classe) e checagem da FK ao
--     remover/alterar turma. Coluna líder id_turma (a UNIQUE existente só
--     atende id_aluno na frente). id_aluno incluído permite index-only scan.
CREATE INDEX idx_matricula_turma_aluno
    ON matricula (id_turma, id_aluno);

-- I2: turmas de um professor em um período. Igualdade nas duas colunas;
--     id_professor primeiro (mais seletivo) e ainda serve consultas só por
--     professor.
CREATE INDEX idx_turma_professor_periodo
    ON turma (id_professor, id_periodo_letivo);

-- I3: oferta de uma disciplina em um período (planejamento de matrícula).
CREATE INDEX idx_turma_disciplina_periodo
    ON turma (id_disciplina, id_periodo_letivo);

-- I4: alunos de um currículo (migração/relatórios de currículo). Seletividade
--     moderada (muitos alunos por currículo, mas fração pequena da tabela).
CREATE INDEX idx_aluno_curriculo
    ON aluno (id_curriculo);

-- (Candidato parcial avaliado e DESCARTADO: curriculo(id_curso) WHERE ativo.
--  O planner ignorou o índice na tabela de 120 linhas: sem ganho, só custo. Ver T6.)

-- I5: trilha de auditoria de uma matrícula em ordem cronológica inversa.
--     Tabela append-only e grande; o composto evita sort e atende FK.
CREATE INDEX idx_log_matricula_matricula_ocorrido
    ON log_matricula (id_matricula, ocorrido_em);


