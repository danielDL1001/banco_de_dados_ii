CREATE TABLE pais (
    id_pais      integer GENERATED BY DEFAULT AS IDENTITY,
    codigo_pais  integer,
    nome_pais    varchar(100)
);

CREATE TABLE estado (
    id_estado    integer GENERATED BY DEFAULT AS IDENTITY,
    id_pais      integer,
    nome_estado  varchar(100),
    municipio    varchar(100)          -- preservado conforme o modelo
);

CREATE TABLE cidade (
    id_cidade      integer GENERATED BY DEFAULT AS IDENTITY,
    nome           varchar(100),
    codigo_cidade  integer,
    id_estado      integer
);

CREATE TABLE campus (
    id_campus     smallint GENERATED BY DEFAULT AS IDENTITY,
    nome_campus   varchar(60),
    cep           varchar(9),          -- nvarchar(9) no modelo (A1)
    endereco      varchar(100),
    telefone      varchar(15),
    complementos  varchar(100),
    qtd_blocos    smallint,
    salas         smallint
);

CREATE TABLE predio (
    id_predio    smallint GENERATED BY DEFAULT AS IDENTITY,
    id_cidade    integer,
    qtd_predios  integer,
    id_campus    smallint
);

CREATE TABLE bloco (
    id_bloco   smallint GENERATED BY DEFAULT AS IDENTITY,
    id_predio  smallint
);

CREATE TABLE sala (
    id_sala     integer GENERATED BY DEFAULT AS IDENTITY,
    codigo      varchar(10),
    capacidade  smallint,
    tipo        varchar(30),
    id_bloco    smallint
);

CREATE TABLE curso (
    id_curso   smallint GENERATED BY DEFAULT AS IDENTITY,
    id_campus  smallint,
    codigo     varchar(10),
    nome       varchar(120),
    grau       varchar(120),
    ch_total   smallint
);

CREATE TABLE curriculo (
    id_curriculo  smallint GENERATED BY DEFAULT AS IDENTITY,
    ano_vigencia  smallint,
    ativo         boolean,
    id_curso      smallint
);

CREATE TABLE disciplina (
    id_disciplina  integer GENERATED BY DEFAULT AS IDENTITY,
    codigo         varchar(10),
    nome           varchar(120),
    ch_teorica     smallint,
    ch_pratica     smallint,
    ch_total       smallint,
    ementa         text
);

CREATE TABLE curriculo_disciplina (
    id_curriculo   smallint NOT NULL,   -- PK/FK
    id_disciplina  integer  NOT NULL,   -- PK/FK
    periodo        smallint,
    tipo           varchar(20)
);

CREATE TABLE pre_requisito (
    id_disciplina  integer NOT NULL,    -- PK/FK
    id_requisito   integer NOT NULL,    -- PK/FK
    vinculo        vinculo_t
);

CREATE TABLE periodo_letivo (
    id_periodo_letivo  smallint GENERATED BY DEFAULT AS IDENTITY,
    ano                smallint,
    semestre           smallint,
    data_inicio        date,
    data_fim           date
);

CREATE TABLE professor (
    id_professor  integer GENERATED BY DEFAULT AS IDENTITY,
    matricula     varchar(12),          -- U
    nome          varchar(120),
    email         varchar(120),
    titulacao     varchar(20)
);

CREATE TABLE turma (
    id_turma           integer GENERATED BY DEFAULT AS IDENTITY,
    id_disciplina      integer,
    id_professor       integer,
    id_periodo_letivo  smallint,
    turno              varchar(10),
    codigo             varchar(15)
);

CREATE TABLE aluno (
    id_aluno      integer GENERATED BY DEFAULT AS IDENTITY,
    id_curriculo  smallint,
    nome          varchar(120),
    cpf           char(11),
    email         varchar(120),         -- U
    nascimento    date
);

CREATE TABLE matricula (
    id_matricula    integer GENERATED BY DEFAULT AS IDENTITY,
    id_aluno        integer NOT NULL,   -- FK/U (A5)
    id_turma        integer NOT NULL,   -- FK/U (A5)
    data_matricula  date,
    status          varchar(15)
);

CREATE TABLE historico (
    id_historico  integer GENERATED BY DEFAULT AS IDENTITY,
    id_matricula  integer NOT NULL,     -- 1:1 obrigatório (A6)
    n1            numeric,              -- A2, A13
    n2            numeric,
    n3            numeric,
    media_final   numeric,
    frequencia    numeric,
    situacao      varchar(15)
);

CREATE TABLE log_matricula (
    id_log         bigint GENERATED BY DEFAULT AS IDENTITY,
    id_matricula   integer,
    acao           varchar(20),
    ocorrido_em    timestamp,
    usuario        varchar(60),
    detalhe        text
);

CREATE TABLE feriado (
    id_feriado  integer GENERATED BY DEFAULT AS IDENTITY,
    data        date,
    descricao   varchar(120)
);

CREATE TABLE pais_feriado (             -- entidade associativa N:N
    fk_id_pais     integer NOT NULL,    -- PFK
    fk_id_feriado  integer NOT NULL     -- PFK (tipo inferido, A3)
);


