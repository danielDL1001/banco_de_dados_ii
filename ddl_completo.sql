-- RESULTADOS REAIS, medidos por execução deste mesmo script em
--   PostgreSQL 16.15 (Ubuntu), 1 vCPU, 4 GB RAM, shared_buffers=128MB,
--   work_mem=4MB, random_page_cost=4, max_parallel_workers_per_gather=2, jit=on,
--   dados SINTÉTICOS (aluno 100 mil, turma 60 mil, matricula 800 mil,
--   historico 800 mil, log_matricula 1,6 mi), cache aquecido (1 execução de
--   aquecimento descartada + 3 registradas; valor = MEDIANA das 3).
-- Tempos absolutos dependem do hardware; o que se transfere é a mudança de plano
-- e de buffers. Medições abaixo de ~0,05 ms têm resolução limitada: o ganho %
-- nesses casos é indicativo, não preciso.
-- Fórmula: Ganho(%) = (Antes - Depois) / Antes * 100  (negativo = regressão)
-- Nenhum valor abaixo é estimado: todos vêm de EXPLAIN (ANALYZE, BUFFERS) reais.

